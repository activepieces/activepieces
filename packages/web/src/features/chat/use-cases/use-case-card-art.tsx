export function UseCaseDoodle({
  id,
  delayMs = 0,
  className,
}: {
  id: string;
  delayMs?: number;
  className?: string;
}) {
  const paths = DOODLE_PATHS[id] ?? FALLBACK_DOODLE;
  const tilt = TILTS[hashId(id) % TILTS.length];

  return (
    <span
      className={cn(
        'inline-flex shrink-0 transition-transform duration-300 ease-out group-hover:-rotate-2 group-hover:scale-110',
        className,
      )}
    >
      <svg
        viewBox="0 0 48 48"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        className="doodle-draw size-full"
        style={{ transform: `rotate(${tilt}deg)` }}
      >
        {paths.map((d, i) => (
          <path
            key={i}
            d={d}
            pathLength={1}
            style={{ animationDelay: `${delayMs + i * 130}ms` }}
          />
        ))}
      </svg>
    </span>
  );
}

