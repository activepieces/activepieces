function hashId(id: string): number {
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash * 31 + id.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function resolveTheme(id: string): UseCaseTheme {
  return INKS[CARD_INKS[id] ?? 'purple'];
}

